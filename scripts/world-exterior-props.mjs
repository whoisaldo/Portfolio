/** The prototypes' parts as the site has them: { name: [{ node, material, geometry }] }. */
function protoParts(core) {
  const parts = new Map();
  for (const node of core.getRoot().listNodes()) {
    const mesh = node.getMesh();
    if (!node.getName().startsWith("proto_") || !mesh) continue;
    const [prim] = mesh.listPrimitives();
    const geometry = new THREE.BufferGeometry();
    for (const semantic of prim.listSemantics()) {
      const a = prim.getAttribute(semantic);
      const name = Object.keys(SEMANTIC).find((k) => SEMANTIC[k] === semantic) ?? semantic;
      geometry.setAttribute(name, new THREE.BufferAttribute(a.getArray(), a.getElementSize(), a.getNormalized()));
    }
    geometry.setIndex(new THREE.BufferAttribute(prim.getIndices().getArray(), 1));
    const object = new THREE.Mesh(geometry);
    object.position.fromArray(node.getTranslation());
    object.quaternion.fromArray(node.getRotation());
    object.scale.fromArray(node.getScale());
    object.updateMatrixWorld(true);
    const proto = node.getExtras()?.proto ?? node.getName().replace(/^proto_/, "").replace(/_[a-z]+(_[a-z]+)?$/, "");
    if (!parts.has(proto)) parts.set(proto, []);
    parts.get(proto).push({ name: node.getName(), material: prim.getMaterial().getName(), assetKind: node.getExtras()?.assetKind ?? "", geometry: mergeMeshes([object], null) });
  }
  return parts;
}

/** A placement's matrix, as props.js decoded() makes it and keeps it. */
function placed(record) {
  const [, x, y, z, yaw, sy, sxz] = record;
  const m = new THREE.Matrix4().compose(
    new THREE.Vector3(x / 20, y / 50, z / 20),
    new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(0, 1, 0), yaw / 10430.2),
    new THREE.Vector3(sxz / 1000, sy / 100, sxz / 1000),
  );
  return Float32Array.from(m.elements);
}

/**
 * `core`: the tier's written core GLB (decoded); `records`: its props
 * file's placements, eight int16s each, in the file's order; `sources`:
 * each record's index in props-source.json; `header`: the file's header;
 * `phone`: the tier. Returns { document, keep, manifest }: the batches'
 * GLB, the records the props file keeps, and what was done.
 */
export function exteriorProps({ core, records, sources, header, phone }) {
  const parts = protoParts(core);
  const kinds = header.protos.map((p) => ({ ...p, reach: (p.reach ?? 5000) * (phone ? 0.65 : 1) }));
  const kindOf = new Map(kinds.map((k, pi) => [k.name, pi]));
  const batches = new Map();
  const taken = [];
  const left = [];
  // (Every triangle of every part of what is taken, counted as it is taken.)
  let triangles = 0;
  records.forEach((record, i) => {
    const k = kinds[record[0]];
    const x = record[1] / 20, z = record[3] / 20;
    const inBox = x >= BOX.x[0] && x <= BOX.x[1] && z >= BOX.z[0] && z <= BOX.z[1];
    const own = [...(parts.get(k.name) ?? []), ...(parts.get(k.name + NEAR) ?? [])];
    if (!inBox || DEALT.has(k.name) || !own.length || own.some((part) => BLENDS.has(clean(part.material)))) {
      if (inBox) left.push({ record: i, source: sources[i], proto: k.name });
      return;
    }
    taken.push(i);
    for (const part of own) triangles += part.geometry.index.count / 3;
    const matrix = placed(record);
    const cell = [Math.floor(x / CELL), Math.floor(z / CELL)];
    const near = kindOf.has(k.name + NEAR) ? (parts.get(k.name + NEAR) ?? []) : [];
    for (const [list, reach, ornament] of [[parts.get(k.name) ?? [], k.reach, false], [near, kinds[kindOf.get(k.name + NEAR)]?.reach, true]]) {
      list.forEach((part, order) => {
        const material = clean(part.material);
        const shaderLocal = OWN.has(material);
        const layers = 1 | (/^(neon_|glow|lantern)/.test(material) || LIT.has(material) ? 1 << REFLECT_LAYER : 0);
        const layout = Object.entries(part.geometry.attributes).map(([name, a]) => name + a.itemSize).sort().join();
        const key = `${part.material}|${layout}|${part.assetKind}|${layers}`;
        if (!batches.has(key)) batches.set(key, { material: part.material, layout, assetKind: part.assetKind, layers, shaderLocal, items: [] });
        batches.get(key).items.push({ record: i, source: sources[i], proto: k.name + (ornament ? NEAR : ""), part: part.name, pi: record[0], ornament, order, reach, cell, matrix, geometry: part.geometry, deal: 0 });
      });
    }
  });

  const document = new Document();
  const buffer = document.createBuffer();
  const scene = document.createScene("exterior_props");
  const materials = new Map();
  const out = [];
  for (const batch of batches.values()) {
    // Cell by cell, row by row across the map (as props.js ranks them), the
    // nearer-only after the rest in a cell; then as the props file has them.
    const rows = [...new Set(batch.items.map((it) => it.cell.join()))].map((c) => c.split(",").map(Number)).sort((a, b) => a[1] - b[1] || a[0] - b[0]);
    const rank = new Map(rows.map((c, r) => [c.join(), r]));
    batch.items.sort((a, b) => rank.get(a.cell.join()) - rank.get(b.cell.join()) || a.reach - b.reach || a.pi - b.pi || a.ornament - b.ornament || a.order - b.order || a.record - b.record);
    const names = Object.keys(batch.items[0].geometry.attributes);
    const verts = batch.items.reduce((n, it) => n + it.geometry.attributes.position.count, 0);
    const indices = batch.items.reduce((n, it) => n + it.geometry.index.count, 0);
    const arrays = Object.fromEntries(names.map((name) => [name, new Float32Array(verts * batch.items[0].geometry.attributes[name].itemSize)]));
    const local = batch.shaderLocal ? { position: new Float32Array(verts * 3), normal: new Float32Array(verts * 3), columns: [0, 1, 2, 3].map(() => new Float32Array(verts * 4)), deal: new Float32Array(verts) } : null;
    const index = verts > 65535 ? new Uint32Array(indices) : new Uint16Array(indices);
    const runs = [];
    const placements = [];
    let v = 0;
    let at = 0;
    for (const it of batch.items) {
      const g = it.geometry;
      const n = g.attributes.position.count;
      const e = it.matrix;
      // (props.js Baked.writeSteps: the instance's frame, by hand.)
      const m0 = e[0], m1 = e[1], m2 = e[2], m4 = e[4], m5 = e[5], m6 = e[6], m8 = e[8], m9 = e[9], m10 = e[10], m12 = e[12], m13 = e[13], m14 = e[14];
      for (const name of names) {
        const from = g.attributes[name].array;
        const to = arrays[name];
        if (name === "position") {
          for (let k = 0, s = 0, d = v * 3; k < n; k++, s += 3, d += 3) {
            const x = from[s], y = from[s + 1], z = from[s + 2];
            to[d] = m0 * x + m4 * y + m8 * z + m12;
            to[d + 1] = m1 * x + m5 * y + m9 * z + m13;
            to[d + 2] = m2 * x + m6 * y + m10 * z + m14;
          }
        } else if (name === "normal") {
          for (let k = 0, s = 0, d = v * 3; k < n; k++, s += 3, d += 3) {
            const x = from[s], y = from[s + 1], z = from[s + 2];
            const nx = m0 * x + m4 * y + m8 * z;
            const ny = m1 * x + m5 * y + m9 * z;
            const nz = m2 * x + m6 * y + m10 * z;
            const l = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;
            to[d] = nx / l;
            to[d + 1] = ny / l;
            to[d + 2] = nz / l;
          }
        } else {
          const size = g.attributes[name].itemSize;
          to.set(from.subarray(0, n * size), v * size);
        }
      }
      if (local) {
        local.position.set(g.attributes.position.array.subarray(0, n * 3), v * 3);
        local.normal.set(g.attributes.normal.array.subarray(0, n * 3), v * 3);
        for (let c = 0; c < 4; c++) for (let k = 0; k < n; k++) local.columns[c].set(e.subarray(c * 4, c * 4 + 4), (v + k) * 4);
        local.deal.fill(it.deal, v, v + n);
      }
      const src = g.index.array;
      for (let k = 0; k < src.length; k++) index[at + k] = src[k] + v;
      const last = runs.at(-1);
      if (last && last[0] === it.cell[0] && last[1] === it.cell[1] && last[2] === it.reach) last[4] += src.length;
      else runs.push([it.cell[0], it.cell[1], it.reach, at, src.length]);
      placements.push([it.record, it.source, it.proto, it.part, at, src.length]);
      v += n;
      at += src.length;
    }
    const accessor = (type, array) => document.createAccessor().setType(type).setArray(array).setBuffer(buffer);
    const TYPE = { 1: "SCALAR", 2: "VEC2", 3: "VEC3", 4: "VEC4" };
    const prim = document.createPrimitive().setIndices(accessor("SCALAR", index));
    for (const name of names) prim.setAttribute(SEMANTIC[name] ?? name, accessor(TYPE[batch.items[0].geometry.attributes[name].itemSize], arrays[name]));
    if (local) {
      prim.setAttribute("_LOCAL_POSITION", accessor("VEC3", local.position));
      prim.setAttribute("_LOCAL_NORMAL", accessor("VEC3", local.normal));
      local.columns.forEach((column, c) => prim.setAttribute(`_INSTANCE_MATRIX_${c}`, accessor("VEC4", column)));
      prim.setAttribute("_DEAL", accessor("SCALAR", local.deal));
    }
    if (!materials.has(batch.material)) materials.set(batch.material, document.createMaterial(batch.material));
    prim.setMaterial(materials.get(batch.material));
    const name = `exterior_props_${clean(batch.material)}_${batch.layers}`;
    const extras = {
      sourceKind: "prop", sourceLayers: batch.layers, visibilitySector: "exterior", shaderLocal: batch.shaderLocal,
      ...(batch.assetKind ? { assetKind: batch.assetKind } : {}),
      // [cell x, cell z, reach, first index, index count]: props.js's runs.
      runs,
      // [props file record, props-source.json instance, prototype, part, first index, index count].
      placements,
    };
    scene.addChild(document.createNode(name).setMesh(document.createMesh(name).addPrimitive(prim)).setExtras(extras));
    out.push({ name, material: batch.material, layout: batch.layout, layers: batch.layers, shaderLocal: batch.shaderLocal, assetKind: batch.assetKind || null,
      vertices: verts, triangles: indices / 3, placements: new Set(placements.map((p) => p[0])).size, parts: placements.length,
      prototypes: [...new Set(placements.map((p) => p[2]))].sort() });
  }
  const gone = new Set(taken);
  return {
    document,
    keep: records.filter((_, i) => !gone.has(i)),
    manifest: { triangles, batches: out, removed: taken.map((i) => ({ record: i, source: sources[i], proto: kinds[records[i][0]].name })), keptInBox: left },
  };
}
