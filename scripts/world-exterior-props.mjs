// scripts/world-exterior-props.mjs: the street's props in front of the
// garage, written out as a few static meshes (B5's round 9 handoff), for
// scripts/optimize-world.mjs.
//
// Seen through the workshop's door, the street's props are a draw each of
// their prototypes and materials (src/world/props.js instances them), a few
// dozen draws for a few hundred triangles. Here each tier's placements in
// BOX are written out as the site would have drawn them, into one mesh a
// batch key (the material, the vertices' layout, the asset kind and the
// render layers it was drawn on), and a props file without those
// placements is written beside the tier's own, so a site that draws the
// meshes and reads that file draws every part once. The site does neither
// yet: B5's consumer chooses both together (exterior-props.json says how).
//
// Every vertex is worked out as the site works it out: the prototype as the
// tier's own GLB carries it, made plain floats where its node stands
// (src/world/merge.js mergeMeshes, as city.js dressProtos does), each
// placement's matrix as props.js decodes its eight int16s (and keeps it, in
// a Float32Array), and the sums of props.js's Baked.writeSteps for its
// position and normal; the other attributes as they are. A prop's own
// material (src/world/prop-surfaces.js: worn, print, face and the rest)
// reads its prototype's own frame, so those batches carry, per vertex, what
// the instanced draw read: the local position and normal, the placement's
// matrix (four columns, as three's instanceMatrix) and its deal (aDeal).
// A prototype the site deals (prop-deal.js RULES: the deal reads its
// neighbours) and a part that blends (glass, a lamp's halo) stay instanced.
import * as THREE from "three";
import { Document } from "@gltf-transform/core";
import { mergeMeshes } from "../src/world/merge.js";
import { RULES } from "../src/world/prop-deal.js";

// B5's first pass: x 410 to 452, z -250 to -180 (the garage's door is at x
// 452), every placement whose decoded x and z are in it.
export const BOX = { x: [410, 452], z: [-250, -180] };
// As props.js: its cells, and the materials that are the props' own.
const CELL = 12;
const OWN = new Set(["plant", "face", "print", "halo", "paper", "worn"]);
// The own materials that read each placement's deal (prop-surfaces.js
// READS), and the lit ones the mirror sees (its LIGHT; a "tube" only on
// the bench strip, which no street prop is).
const LIT = new Set(["face", "paper"]);
// What blends, drawn in an order: left as it is.
const BLENDS = new Set(["clearglass", "halo"]);
const DEALT = new Set(RULES.flatMap((rule) => rule.protos));
// city.js REFLECT_LAYER: the wet road's mirror draws what is on it.
const REFLECT_LAYER = 2;
const NEAR = "__near";
const clean = (name) => name.replace(/^NCW_/, "").replace(/\.\d+$/, "");
const SEMANTIC = { position: "POSITION", normal: "NORMAL", uv: "TEXCOORD_0", color: "COLOR_0" };

// What design/night-city-world/exterior-props.json says of the files, for
