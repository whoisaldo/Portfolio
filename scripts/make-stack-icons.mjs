const BONE = [236, 234, 228];
const srgb = (c) => { const s = c / 255; return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4; };
const lum = ([r, g, b]) => 0.2126 * srgb(r) + 0.7152 * srgb(g) + 0.0722 * srgb(b);
const hexToRgb = (h) => [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
const toHex = (rgb) => "#" + rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

// Mix toward bone until the mark clears the floor. 0.16 is roughly a 4:1
// contrast against #0a0a0c, which is the bar for a graphic you have to
// recognise rather than read.
function lift(hex) {
  let rgb = hexToRgb(hex);
  let t = 0;
  while (lum(rgb) < 0.16 && t < 1) {
    t += 0.05;
    rgb = hexToRgb(hex).map((c, i) => c + (BONE[i] - c) * t);
  }
  return toHex(rgb);
}

const bySlug = new Map(Object.values(si).filter((i) => i && i.slug).map((i) => [i.slug, i]));

const out = {};
const missing = [];
for (const [name, ref] of Object.entries(MAP)) {
  if (Array.isArray(ref)) {
    out[name] = { mono: ref[0] };
    continue;
  }
  const icon = bySlug.get(ref);
  if (!icon) { missing.push(`${name} -> ${ref}`); out[name] = { mono: name.slice(0, 3).toUpperCase() }; continue; }
  out[name] = { path: icon.path, color: lift(icon.hex), title: icon.title };
}

if (missing.length) {
  console.error("simple-icons has no slug for:\n  " + missing.join("\n  "));
  process.exitCode = 1;
}

const body = Object.entries(out)
  .map(([name, v]) => `  ${JSON.stringify(name)}: ${JSON.stringify(v)},`)
  .join("\n");

writeFileSync(
  new URL("../src/data/stack-icons.js", import.meta.url),
  `// GENERATED by scripts/make-stack-icons.mjs. Do not edit by hand.
//
// One entry per item in \`skills\` (src/data/profile.js). Either a 24x24
// single-path mark from simple-icons with a colour lifted clear of the carbon
// ground, or \`mono\`: the letters to set in a monogram tile, for the marks
// that do not exist as a licensed icon (AWS, OpenAI, C#, PowerShell, VS Code)
// or that are APIs rather than brands (DXGI, Metal, VideoToolbox, H.264).
//
// Regenerate with \`npm run icons\`. simple-icons is a devDependency and is
// never imported at runtime.
export const stackIcons = {
${body}
};

export const iconFor = (name) => stackIcons[name] ?? { mono: name.slice(0, 2).toUpperCase() };
`,
);

