// scripts/make-stack-icons.mjs: bake the stack marks into src/data/stack-icons.js.
//
// The Stack section shows a real logo beside each entry. Three ways to do
// that and only one of them is defensible:
//
//   - <img> per logo from a CDN. Sixty network requests for decoration, and a
//     third-party origin that gets told every time someone reads this page.
//   - import { siRust } from "simple-icons" at runtime. Vite would have to
//     pull a 3,460-icon index into the graph to tree-shake fifty out of it,
//     and the dev server pays that on every cold start.
//   - this. Run it by hand, commit the output, ship 50 path strings.
//
// simple-icons is a devDependency for exactly this reason: `npm run icons`
// regenerates the file, nothing imports the package at runtime.
//
// NOT EVERY MARK EXISTS. simple-icons removed a number of them over
// trademark policy (AWS, OpenAI, C#, PowerShell, VS Code), and some entries
// here are APIs rather than brands (DXGI, VideoToolbox, H.264). Those get
// `null` and the component draws a monogram instead. A monogram is honest.
// Drawing Microsoft's logo from memory would not be.
//
// COLOUR. Brand hexes are chosen against white. Seven of these are pure or
// near black, which is invisible on #0a0a0c, so anything darker than a
// luminance floor is mixed toward bone until it clears it. The mark still
// reads as the brand's own colour where the brand has one.
