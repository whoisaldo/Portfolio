// scripts/optimize-door-car.mjs: the door's S4, compressed for the browser.
//
// After scripts/blender/build_s4_door.py has written design/audi-s4/door-source.glb
// (git-ignored, as the main S4's source is): the same pass as optimize-s4.mjs,
// with the AO the bake left in the vertex colours kept at eight bits, and the
// revision written to src/data/door-car.js.
import { readFile, stat, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { dedup, meshopt, prune, weld } from "@gltf-transform/functions";
import { MeshoptEncoder } from "meshoptimizer";

const source = "design/audi-s4/door-source.glb";
const output = "public/models/ali-s4-door.glb";
await MeshoptEncoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ "meshopt.encoder": MeshoptEncoder });
const document = await io.read(source);
// Texture coordinates only where a texture reads them: most of the car is
// plain colour, and unused UVs were most of the file.
for (const mesh of document.getRoot().listMeshes()) {
  for (const prim of mesh.listPrimitives()) {
    const m = prim.getMaterial();
    const textured = m && (m.getBaseColorTexture() || m.getNormalTexture() || m.getMetallicRoughnessTexture() || m.getOcclusionTexture() || m.getEmissiveTexture());
    if (!textured) for (const s of prim.listSemantics()) if (s.startsWith("TEXCOORD") || s === "TANGENT") prim.setAttribute(s, null);
  }
}
await document.transform(
  prune(),
  dedup(),
  weld(),
  meshopt({ encoder: MeshoptEncoder, level: "high", quantizePosition: 14, quantizeNormal: 10, quantizeTexcoord: 12, quantizeColor: 8 }),
);
await io.write(output, document);
const revision = createHash("sha256").update(await readFile(output)).digest("hex").slice(0, 12);
const metadata = `// Generated by scripts/optimize-door-car.mjs.\nexport const doorCarUrl = "/models/ali-s4-door.glb?v=${revision}";\n`;
const metadataPath = "src/data/door-car.js";
if ((await readFile(metadataPath, "utf8").catch(() => "")) !== metadata) await writeFile(metadataPath, metadata);
const before = (await stat(source)).size;
const after = (await stat(output)).size;
console.log(`Door S4: ${(before / 1e6).toFixed(2)} MB → ${(after / 1e6).toFixed(2)} MB.`);
