_USED = {}   # a word -> where it hangs


def pick(pool, c, n=None, spread=(0, 99)):
    """A word for a sign at c: of `pool` (of `n` characters, give or take
    `spread`), the one whose last hanging is furthest away."""
    lo, hi = (n - spread[0], n + spread[1]) if n is not None else (0, 99)
    fit = [w for w in pool if lo <= len(w) <= hi] or list(pool)
    h = int(abs(c[0] * 7.3 + c[1] * 3.1 + c[2] * 11.7))
    best, bd = fit[0], -1.0
    for j in range(len(fit)):
        w = fit[(j + h) % len(fit)]
        d = min(((p[0] - c[0]) ** 2 + (p[2] - c[2]) ** 2 for p in _USED.get(w, ())), default=1e12)
        if d > bd:
            best, bd = w, d
    _USED.setdefault(best, []).append(c)
    return best


def segments(text, w, h, vertical=False, gap=0.22):
    """The strokes of `text` set in a w x h box centred on the origin: a
    list of ((u0, v0), (u1, v1)), u across and v up. Across, each character
    has w / n; down a column, h / n."""
    n = max(1, len(text))
    cw, ch = (w, h / n) if vertical else (w / n, h)
    gw, gh = cw * (1.0 - gap), ch * (1.0 - (gap if vertical else 0.0))
    out = []
    for i, c in enumerate(text):
        if vertical:
            ox, oy = -gw / 2, h / 2 - (i + 0.5) * ch - gh / 2
            c = "|" if c == "ー" else c
        else:
            ox, oy = -w / 2 + (i + 0.5) * cw - gw / 2, -gh / 2
        for line in GLYPHS.get(c, []):
            for (xa, ya), (xb, yb) in zip(line, line[1:]):
                out.append(((ox + xa * gw, oy + ya * gh), (ox + xb * gw, oy + yb * gh)))
    return out
